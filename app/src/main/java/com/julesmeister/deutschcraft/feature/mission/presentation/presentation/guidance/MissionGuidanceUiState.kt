package com.julesmeister.deutschcraft.feature.mission.presentation.guidance

import com.julesmeister.deutschcraft.feature.mission.domain.ActiveMissionConversationContext
import com.julesmeister.deutschcraft.feature.mission.data.ai.MissionLanguageSupport
import com.julesmeister.deutschcraft.core.cefr.model.CefrLevel

/*
 * Presentation state for learner-facing mission guidance.
 *
 * This is deliberately separate from:
 *
 * - ConversationMission
 * - Room entities
 * - AI prompts
 *
 * Only assistance explicitly revealed through the guidance
 * UI should count as learner assistance for analytics.
 */
data class MissionGuidanceUiState(

    /*
     * Controls whether the mission header details are expanded.
     *
     * An active mission does not automatically expand the header.
     *
     * The learner toggles it with the mission header chevron.
     */
    val isVisible: Boolean =
        false,

    val missionId: String? =
        null,

    val missionTitle: String =
        "",

    val objectiveId: String? =
        null,

    val objectiveTitle: String =
        "",

    val objectiveDescription: String =
        "",

    val progressPercentage: Int =
        0,

    /*
     * All available support content for the current
     * objective.
     *
     * coachingHints itself is never automatically displayed.
     *
     * revealedHints contains only assistance that the learner
     * explicitly requested.
     */
    val coachingHints:
    List<String> =
        emptyList(),

    /*
     * Hints already revealed to the learner.
     *
     * These correspond to persisted mission-objective hint
     * usage and therefore affect independence analytics.
     */
    val revealedHints:
    List<String> =
        emptyList(),

    /*
     * Useful vocabulary associated with the current objective.
     *
     * Opening the vocabulary section should not count as a
     * progressive coaching hint unless we later explicitly
     * decide to model it as assistance.
     */
    val targetVocabulary:
    List<String> =
        emptyList(),

    /*
     * Suggested phrases for the current objective.
     */
    val examplePhrases:
    List<String> =
        emptyList(),

    /*
     * UI-only expansion states.
     */
    val isVocabularyVisible: Boolean =
        false,

    val isExamplesVisible: Boolean =
        false,

    /*
     * True while a new coaching hint is being persisted.
     *
     * Hint persistence is local Room I/O, but preventing
     * repeated taps avoids accidentally revealing multiple
     * assistance levels at once.
     */
    val isRevealingHint: Boolean =
        false,

    /*
     * Learner-facing error generated by a guidance operation.
     *
     * This should normally remain null.
     */
    val errorMessage: String? =
        null,

    val scenario: String = "",
    val cefrLevel: CefrLevel? = null,
    val objectives: List<MissionGuidanceGoal> = emptyList(),
    val languageSupport: MissionLanguageSupport? = null,
    val isLoadingLanguageSupport: Boolean = false,
    val languageSupportError: String? = null
) {

    /*
     * Guidance requires both:
     *
     * - an active conversation mission
     * - a current objective
     */
    val hasActiveMission: Boolean
        get() =
            !missionId.isNullOrBlank() &&
                    !objectiveId.isNullOrBlank()

    val safeProgressPercentage: Int
        get() =
            progressPercentage.coerceIn(
                minimumValue =
                    0,
                maximumValue =
                    100
            )

    val revealedHintCount: Int
        get() =
            revealedHints
                .size
                .coerceIn(
                    minimumValue =
                        0,
                    maximumValue =
                        MAXIMUM_HINT_COUNT
                )

    /*
     * Whether the learner can request another coaching hint.
     */
    val hasMoreHints: Boolean
        get() =
            revealedHintCount <
                    coachingHints.size &&
                    revealedHintCount <
                    MAXIMUM_HINT_COUNT

    /*
     * Index of the next coaching hint to reveal.
     *
     * Example:
     *
     * 0 revealed -> index 0
     * 1 revealed -> index 1
     * 2 revealed -> index 2
     * 3 revealed -> null
     */
    val nextHintIndex: Int?
        get() {
            if (!hasMoreHints) {
                return null
            }

            return revealedHintCount
        }

    /*
     * Assistance level represented by explicitly revealed
     * progressive hints.
     *
     * This is later consumed by independence analytics.
     */
    val assistanceLevel:
            MissionAssistanceLevel
        get() =
            when (revealedHintCount) {
                0 -> {
                    MissionAssistanceLevel
                        .INDEPENDENT
                }

                1 -> {
                    MissionAssistanceLevel
                        .GENTLE
                }

                2 -> {
                    MissionAssistanceLevel
                        .CONTEXTUAL
                }

                else -> {
                    MissionAssistanceLevel
                        .DIRECT
                }
            }

    companion object {

        /*
         * Assistance model:
         *
         * Level 0
         * Independent
         *
         * Level 1
         * Gentle support
         *
         * Level 2
         * Contextual support
         *
         * Level 3
         * Direct support
         */
        const val MAXIMUM_HINT_COUNT =
            3

        /*
         * Builds guidance for the current active mission.
         *
         * The sheet remains CLOSED when mission state changes.
         *
         * This prevents Room emissions from unexpectedly
         * opening UI over the conversation.
         */
        fun from(
            context:
            ActiveMissionConversationContext
        ): MissionGuidanceUiState {
            val objective =
                context.currentObjective

            return MissionGuidanceUiState(
                isVisible =
                    false,

                missionId =
                    context.missionId,

                missionTitle =
                    context
                        .title
                        .trim(),

                objectiveId =
                    objective.id,

                objectiveTitle =
                    objective
                        .title
                        .trim(),

                objectiveDescription =
                    objective
                        .description
                        .trim(),

                progressPercentage =
                    context
                        .safeProgressPercentage,

                coachingHints =
                    objective
                        .coachingHints
                        .sanitizedValues(
                            maximumSize =
                                MAXIMUM_HINT_COUNT
                        ),

                /*
                 * Persisted hint usage is restored separately
                 * by MissionGuidanceController.
                 *
                 * Do not automatically expose every available
                 * coaching hint.
                 */
                revealedHints =
                    emptyList(),

                targetVocabulary =
                    objective
                        .targetVocabulary
                        .sanitizedValues(
                            maximumSize =
                                MAXIMUM_VOCABULARY_COUNT
                        ),

                examplePhrases =
                    objective
                        .examplePhrases
                        .sanitizedValues(
                            maximumSize =
                                MAXIMUM_EXAMPLE_COUNT
                        ),

                isVocabularyVisible =
                    false,

                isExamplesVisible =
                    false,

                isRevealingHint =
                    false,

                errorMessage =
                    null
            )
        }

        private const val MAXIMUM_VOCABULARY_COUNT =
            4

        private const val MAXIMUM_EXAMPLE_COUNT =
            2

        /*
         * Removes blank and duplicate values and limits the
         * amount of support content presented at once.
         */
        private fun List<String>.sanitizedValues(
            maximumSize: Int
        ): List<String> {
            if (maximumSize <= 0) {
                return emptyList()
            }

            return asSequence()
                .map(
                    String::trim
                )
                .filter(
                    String::isNotBlank
                )
                .distinct()
                .take(
                    maximumSize
                )
                .toList()
        }
    }
}

/*
 * Amount of objective assistance the learner explicitly
 * requested.
 *
 * This is intentionally based on revealed coaching hints,
 * rather than simply having guidance available.
 */
data class MissionGuidanceGoal(val id: String, val title: String, val isCompleted: Boolean)

enum class MissionAssistanceLevel {
    INDEPENDENT,
    GENTLE,
    CONTEXTUAL,
    DIRECT
}