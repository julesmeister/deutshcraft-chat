package com.julesmeister.deutschcraft.feature.adaptivelearning.domain

import android.util.Log
import com.julesmeister.deutschcraft.core.cefr.model.CefrLevel
import com.julesmeister.deutschcraft.core.database.entity.DetectedMistakeEntity
import com.julesmeister.deutschcraft.feature.adaptivelearning.data.mapper.ChatMessageAdaptiveConversationMapper
import com.julesmeister.deutschcraft.feature.adaptivelearning.domain.model.AdaptiveLearningFeedback
import com.julesmeister.deutschcraft.feature.adaptivelearning.domain.model.AdaptiveLearningMessageResult
import com.julesmeister.deutschcraft.feature.adaptivelearning.domain.usecase.EvaluateCommunicationEvidenceUseCase
import com.julesmeister.deutschcraft.feature.adaptivelearning.domain.usecase.GenerateAdaptiveFocusesUseCase
import com.julesmeister.deutschcraft.feature.chat.domain.ChatMessage
import com.julesmeister.deutschcraft.feature.chat.domain.MessageSender
import javax.inject.Inject
import kotlinx.coroutines.CancellationException

/*
 * Main adaptive-learning entry point for one completed
 * learner-message assessment.
 *
 * It combines:
 *
 * 1. Grammar and vocabulary mistakes already detected by the
 *    assessment system.
 *
 * 2. CEFR communication evidence generated by Qwen.
 *
 * 3. Persistent mastery updates through the existing
 *    adaptive-learning use cases.
 *
 * Adaptive learning is supplementary. A failure here must
 * never make the normal chat send operation fail.
 */
class AdaptiveLearningChatCoordinator
@Inject constructor(
    private val conversationMapper:
    ChatMessageAdaptiveConversationMapper,
    private val evaluateCommunicationEvidence:
    EvaluateCommunicationEvidenceUseCase,
    private val generateAdaptiveFocuses:
    GenerateAdaptiveFocusesUseCase
) {

    suspend fun process(
        learnerMessage: ChatMessage,
        conversationId: String?,
        cefrLevel: CefrLevel,
        recentMessages: List<ChatMessage>,
        detectedMistakes:
        List<DetectedMistakeEntity>
    ): AdaptiveLearningMessageResult {
        val skipReason =
            determineSkipReason(
                learnerMessage =
                    learnerMessage
            )

        if (skipReason != null) {
            Log.d(
                COORDINATOR_TAG,
                "Adaptive-learning processing skipped: " +
                        skipReason
            )

            return AdaptiveLearningMessageResult(
                skippedObservationCount =
                    detectedMistakes.size
            )
        }

        return try {
            val conversationContext =
                conversationMapper.mapRecent(
                    messages =
                        recentMessages,
                    latestLearnerMessageId =
                        learnerMessage.id
                )

            Log.d(
                COORDINATOR_TAG,
                buildString {
                    append("Starting adaptive learning. ")
                    append("messageId=")
                    append(learnerMessage.id)
                    append(", level=")
                    append(cefrLevel.name)
                    append(", recentTurns=")
                    append(conversationContext.size)
                    append(", detectedMistakes=")
                    append(detectedMistakes.size)
                }
            )

            val communicationEvidenceBatch =
                evaluateCommunicationEvidence(
                    learnerMessage =
                        learnerMessage.content,
                    cefrLevel =
                        cefrLevel,
                    recentConversation =
                        conversationContext
                )

            val result =
                generateAdaptiveFocuses(
                    messageId =
                        learnerMessage.id,
                    conversationId =
                        conversationId,
                    targetCefrLevel =
                        cefrLevel,
                    mistakes =
                        detectedMistakes,
                    communicationEvidence =
                        communicationEvidenceBatch.evidence
                )

            logResult(
                learnerMessage =
                    learnerMessage,
                result =
                    result,
                communicationEvidenceCount =
                    communicationEvidenceBatch
                        .usableEvidence
                        .size
            )

            result
        } catch (
            cancellationException:
            CancellationException
        ) {
            throw cancellationException
        } catch (throwable: Throwable) {
            /*
             * The message, assistant response, and standard
             * CEFR assessment may already have succeeded.
             *
             * Adaptive learning must not invalidate those
             * successful operations.
             */
            Log.e(
                COORDINATOR_TAG,
                "Adaptive-learning chat processing failed.",
                throwable
            )

            AdaptiveLearningMessageResult(
                failedObservationCount =
                    detectedMistakes.size
                        .coerceAtLeast(
                            minimumValue =
                                1
                        )
            )
        }
    }

    suspend fun processAndReturnFeedback(
        learnerMessage: ChatMessage,
        conversationId: String?,
        cefrLevel: CefrLevel,
        recentMessages: List<ChatMessage>,
        detectedMistakes:
        List<DetectedMistakeEntity>
    ): AdaptiveLearningFeedback? {
        return process(
            learnerMessage =
                learnerMessage,
            conversationId =
                conversationId,
            cefrLevel =
                cefrLevel,
            recentMessages =
                recentMessages,
            detectedMistakes =
                detectedMistakes
        ).feedback
    }

    private fun determineSkipReason(
        learnerMessage: ChatMessage
    ): String? {
        return when {
            learnerMessage.sender !=
                    MessageSender.USER -> {

                "Message sender is not USER."
            }

            learnerMessage.id.isBlank() -> {
                "Learner message ID is blank."
            }

            learnerMessage.content.isBlank() -> {
                "Learner message content is blank."
            }

            else -> {
                null
            }
        }
    }

    private fun logResult(
        learnerMessage: ChatMessage,
        result: AdaptiveLearningMessageResult,
        communicationEvidenceCount: Int
    ) {
        Log.d(
            COORDINATOR_TAG,
            buildString {
                append("Adaptive learning completed. ")
                append("messageId=")
                append(learnerMessage.id)
                append(", communicationEvidence=")
                append(communicationEvidenceCount)
                append(", recordedFocuses=")
                append(result.recordedFocusCount)
                append(", skipped=")
                append(result.skippedObservationCount)
                append(", failed=")
                append(result.failedObservationCount)
                append(", feedbackType=")
                append(result.feedback?.type)
                append(", feedbackMessage=")
                append(result.feedback?.message)
            }
        )

        result.recordedFocuses.forEach { focus ->
            Log.d(
                COORDINATOR_TAG,
                buildString {
                    append("Updated focus: ")
                    append("key=")
                    append(focus.focusKey)
                    append(", state=")
                    append(focus.masteryState)
                    append(", mastery=")
                    append(focus.masteryPercentage)
                    append("%")
                    append(", evidence=")
                    append(focus.safeEvidenceCount)
                    append(", struggles=")
                    append(focus.safeStruggleCount)
                    append(", successes=")
                    append(focus.safeSuccessCount)
                }
            )
        }
    }

    private companion object {
        const val COORDINATOR_TAG =
            "AdaptiveLearningChat"
    }
}